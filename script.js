
const skillsList = [
    "HTML",
    "CSS",
    "JavaScript",
    "Java",
    "Python",
    "C++",
    "SQL",
    "React",
    "Node.js",
    "Git",
    "GitHub",
    "Communication",
    "Problem Solving",
    "Data Structures",
    "OOP",
    "Excel",
    "Machine Learning"
];

function analyzeSkills() {
    const jobText = document
        .getElementById("jobDescription")
        .value.toLowerCase();

    const userText = document
        .getElementById("mySkills")
        .value.toLowerCase();

    if (!jobText.trim() || !userText.trim()) {
        alert("Please enter both the job description and your skills.");
        return;
    }

    const requiredSkills = skillsList.filter(skill =>
        jobText.includes(skill.toLowerCase())
    );

    const matched = requiredSkills.filter(skill =>
        userText.includes(skill.toLowerCase())
    );

    const missing = requiredSkills.filter(skill =>
        !matched.includes(skill)
    );

    const percentage = requiredSkills.length === 0
        ? 0
        : Math.round((matched.length / requiredSkills.length) * 100);

const learningResources = {
    "HTML": "Learn HTML structure, forms, and semantic tags.",
    "CSS": "Learn Flexbox, Grid, and responsive design.",
    "JavaScript": "Practice variables, functions, arrays, and DOM.",
    "Java": "Study OOP, collections, and exception handling.",
    "Python": "Practice Python syntax, functions, and projects.",
    "C++": "Learn pointers, OOP, and STL basics.",
    "SQL": "Practice SELECT, JOIN, GROUP BY, and queries.",
    "React": "Learn components, props, state, and hooks.",
    "Node.js": "Study server-side JavaScript and APIs.",
    "Git": "Practice commits, branches, and merging.",
    "GitHub": "Learn repositories, pull requests, and Pages.",
    "Communication": "Practice clear speaking and writing.",
    "Problem Solving": "Solve beginner coding problems regularly.",
    "Data Structures": "Study arrays, linked lists, stacks, and queues.",
    "OOP": "Learn classes, objects, inheritance, and polymorphism.",
    "Excel": "Practice formulas, sorting, and pivot tables.",
    "Machine Learning": "Start with Python, data, and basic ML models."
};

const roadmap = document.getElementById("learningRoadmap");

roadmap.innerHTML = missing.length
    ? missing.map((skill, index) => `
        <div class="roadmap-item">
            <strong>Step ${index + 1}: ${skill}</strong>
            <p>${learningResources[skill] || "Study the fundamentals and build a small project."}</p>
        </div>
      `).join("")
    : "<p>Great! No recognized skill gaps to work on.</p>";

    document.getElementById("percentage").textContent =
        requiredSkills.length === 0 ? "N/A" : percentage + "%";

    document.getElementById("matchedSkills").innerHTML =
        matched.length
            ? matched.map(skill =>
                `<span class="skill matched">${skill}</span>`
              ).join("")
            : "No matched skills found.";

    document.getElementById("missingSkills").innerHTML =
        missing.length
            ? missing.map(skill =>
                `<span class="skill missing">${skill}</span>`
              ).join("")
            : requiredSkills.length
                ? "No missing skills!"
                : "No recognized skills found in the job description.";

    document.getElementById("results").hidden = false;
}

function downloadReport() {
    const percentage = document.getElementById("percentage").textContent;
    const matched = document.getElementById("matchedSkills").innerText;
    const missing = document.getElementById("missingSkills").innerText;
    const roadmap = document.getElementById("learningRoadmap").innerText;

    const report = `
JOB DESCRIPTION SKILL GAP ANALYZER
==================================

SKILL MATCH: ${percentage}

MATCHED SKILLS:
${matched}

MISSING SKILLS:
${missing}

LEARNING ROADMAP:
${roadmap}

==================================
Generated by Skill Gap Analyzer
`;

    const blob = new Blob([report], {
        type: "text/plain;charset=utf-8"
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = "Skill_Gap_Report.txt";
    link.click();

    URL.revokeObjectURL(url);
}